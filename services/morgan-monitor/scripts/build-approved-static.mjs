/** Embed only the reviewed graph assets. Run after edits and before deployment. */
import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const html = ['public/approved-index.html', 'text/html; charset=utf-8'];
const routes = {
  '/':html, '/index.html':html, '/approved-index.html':html,
  '/approved-app.js':['public/approved-app.js','text/javascript; charset=utf-8'],
  '/approved-styles.css':['public/approved-styles.css','text/css; charset=utf-8'],
  '/lib/session-runtime.js':['public/lib/session-runtime.js','text/javascript; charset=utf-8'],
  '/lib/approved-graph.js':['public/lib/approved-graph.js','text/javascript; charset=utf-8'],
  '/lib/approved-geometry.js':['public/lib/approved-geometry.js','text/javascript; charset=utf-8'],
  '/lib/approved-assets.js':['public/lib/approved-assets.js','text/javascript; charset=utf-8'],
};
const assets = {};
for (const [route,[file,contentType]] of Object.entries(routes)) assets[route] = {contentType,body:await readFile(new URL(file, root),'utf8')};
await writeFile(new URL('approved-static-source.mjs', root), '// Generated by scripts/build-approved-static.mjs; exact reviewed static route allowlist.\nexport const APPROVED_STATIC = Object.freeze(' + JSON.stringify(assets) + ');\n');
console.log('Embedded ' + Object.keys(assets).length + ' reviewed routes.');
